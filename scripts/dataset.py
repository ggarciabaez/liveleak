import json
from pathlib import Path
import numpy as np
import torch
from torch.utils.data import Dataset


class ContiguousTrajectoryDataset(Dataset):
    def __init__(
        self,
        npz_paths: list[str | Path],
        window_size: int = 9,
        window_stride: int = 1,
        cone_grid_norm: float = 32.0 / 640.0,  # 0.05 normalized grid cell (equiv to 32px at 640p)
         require_shared_entity: bool = False,
    ):
        """
        Args:
            npz_paths: List of .npz files generated by detect.py.
            window_size: Total frames per window (W). Last history frame is W-2, target is W-1.
            window_stride: Step size between consecutive windows.
            cone_grid_norm: Grid size in [0, 1] normalized coordinates for static cone ID hashing.
            require_shared_entity: If True, requires at least one *same* ID in both W-2 and W-1.
                                   If False, requires at least one entity present in W-2 AND at least one in W-1.
        """
        self.window_size = window_size
        self.cone_grid_norm = cone_grid_norm
        self.videos = []
        self.index = []  # List of (video_idx, start_frame)

        for path in npz_paths:
            data = np.load(path, allow_pickle=False)
            rows = data["rows"].astype(np.float32, copy=True)
            frame_ptr = data["frame_ptr"]
            meta = json.loads(str(data["metadata"]))

            w, h = float(meta["width"]), float(meta["height"])
            num_frames = len(frame_ptr) - 1
            if num_frames < window_size or len(rows) == 0:
                continue

            # 1. Normalize coordinates (px, py, vx, vy) in-place at load time
            rows[:, 5] /= w  # px
            rows[:, 6] /= h  # py
            rows[:, 7] /= w  # vx
            rows[:, 8] /= h  # vy

            # 2. Assign scale-independent spatial IDs to cones (where id == -1)
            cone_mask = rows[:, 0] == -1
            if cone_mask.any():
                gx = np.floor(rows[cone_mask, 5] / self.cone_grid_norm).astype(np.int64)
                gy = np.floor(rows[cone_mask, 6] / self.cone_grid_norm).astype(np.int64)
                rows[cone_mask, 0] = -(2 + gx * 10000 + gy)

            vid_idx = len(self.videos)
            self.videos.append({"rows": rows, "frame_ptr": frame_ptr, "meta": meta})

            # 3. Filter empty windows during indexing
            for start_f in range(0, num_frames - window_size + 1, window_stride):
                last_hist_f = start_f + window_size - 2
                target_f = start_f + window_size - 1

                n_hist = frame_ptr[last_hist_f + 1] - frame_ptr[last_hist_f]
                n_targ = frame_ptr[target_f + 1] - frame_ptr[target_f]

                # Skip if either the last history frame or the target frame is empty
                if n_hist == 0 or n_targ == 0:
                    continue

                if require_shared_entity:
                    ids_hist = rows[frame_ptr[last_hist_f] : frame_ptr[last_hist_f + 1], 0]
                    ids_targ = rows[frame_ptr[target_f] : frame_ptr[target_f + 1], 0]
                    if np.intersect1d(ids_hist, ids_targ).size == 0:
                        continue

                self.index.append((vid_idx, start_f))

    def __len__(self) -> int:
        return len(self.index)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        vid_idx, start_f = self.index[idx]
        vid = self.videos[vid_idx]
        rows = vid["rows"]
        ptr = vid["frame_ptr"]
        W = self.window_size

        # Slice the exact contiguous block of rows for frames [start_f, start_f + W)
        r_start = ptr[start_f]
        r_end = ptr[start_f + W]
        window_rows = rows[r_start:r_end]

        # Unique entity IDs across this window
        unique_ids, inverse_indices = np.unique(window_rows[:, 0], return_inverse=True)
        N = len(unique_ids)

        feats = np.zeros((W, N, 13), dtype=np.float32)
        feats[..., 0] = -1.0
        valid = np.zeros((W, N), dtype=bool)

        # Populate (W, N, 13) using local pointer offsets
        for t in range(W):
            local_s = ptr[start_f + t] - r_start
            local_e = ptr[start_f + t + 1] - r_start
            if local_e > local_s:
                slots = inverse_indices[local_s:local_e]
                feats[t, slots] = window_rows[local_s:local_e]
                valid[t, slots] = True

        return torch.from_numpy(feats), torch.from_numpy(valid)